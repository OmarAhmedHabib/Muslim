  // ===== دالة الحصول على رقم اليوم في السنة =====
  function getDayOfYear() {
    var now = new Date();
    var start = new Date(now.getFullYear(), 0, 0);
    var diff = now - start;
    var oneDay = 1000 * 60 * 60 * 24;
    return Math.floor(diff / oneDay);
  }

  // ===== دالة الحصول على 7 خواطر لهذا اليوم =====
  function getDailyKhawatir() {
    var dayOfYear = getDayOfYear();
    var total = KHawatir.length;
    var start = (dayOfYear * 7) % total;
    var result = [];

    for (var i = 0; i < 7; i++) {
      var index = (start + i) % total;
      result.push(KHawatir[index]);
    }

    return result;
  }

